#!/usr/bin/env python3
"""Generate original vocal music through ACE-Step 1.5 official Hugging Face Gradio Space."""
import argparse,os,json,pathlib,subprocess,sys
from gradio_client import Client
def main():
 p=argparse.ArgumentParser();p.add_argument("--song",default="studio/song.json");p.add_argument("--out",default="offtherecord-original-vocals-59s.mp3");a=p.parse_args()
 client=Client(os.getenv("HF_MUSIC_SPACE","ACE-Step/Ace-Step-v1.5"),token=os.getenv("HF_TOKEN") or None)
 if os.getenv("HF_INSPECT_API")=="1":
  client.view_api();return
 song=json.loads(pathlib.Path(a.song).read_text())
 # Parameters verified against ACE-Step v1.5 Gradio API, /generation_wrapper (2026-11-08).
 # Generation mode 'custom' supplies user lyrics rather than autogenerated words.
 params=[
 "acestep-v15-xl-turbo","custom",song["prompt"],"en",song["prompt"],song["lyrics"],
 song["bpm"],song["key_scale"],"4","en",8,7.0,True,"-1",None,
 59,1,None,"",0.0,-1,"Fill the audio semantic mask based on the given conditions:",
 1.0,"text2music",False,0.0,1.0,3.0,"ode","","mp3",0.85,
 False,2.0,0,0.9,"NO USER INPUT",True,True,True,False,True,False,
 False,0.5,8,"vocals",[],False
 ]
 if len(params)!=49:raise AssertionError("ACE-Step argument count mismatch")
 print("Submitting original sung song to ACE-Step cloud...")
 result=client.predict(*params,api_name="/generation_wrapper")
 if not isinstance(result,(tuple,list)) or not result:raise RuntimeError("Unexpected generation response")
 audio=result[0]
 if isinstance(audio,dict):audio=audio.get("path") or audio.get("name")
 if not isinstance(audio,str) or not pathlib.Path(audio).is_file():
  status=result[10] if len(result)>10 else "unknown"
  raise RuntimeError("No generated audio file. Generator status: "+str(status)[:1000])
 subprocess.run(["ffmpeg","-hide_banner","-loglevel","error","-y","-i",audio,
  "-af","apad,atrim=0:59,afade=t=in:st=0:d=1.2,afade=t=out:st=57.8:d=1.2",
  "-t","59","-codec:a","libmp3lame","-b:a","256k",a.out],check=True)
 print("Original 59-second vocal song generated:",a.out)
if __name__=="__main__":main()
